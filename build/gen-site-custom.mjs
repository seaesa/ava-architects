// Extract the site's own hand-authored stylesheet (the `/* Custom CSS */`
// block the theme customiser serves inline) and emit it as a formatted,
// asset-rewritten partial. These rules are the site's bespoke design layer —
// everything Flatsome does not give you by default — so the clone needs them
// to match. Everything before the marker is theme configuration, which the
// hand-written partials in src/css already reproduce from measurements.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { cacheKey } from './crawl.mjs';
import { localPath } from './paths.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const MARKER = '/* Custom CSS */';

const html = readFileSync(join(ROOT, '.cache', cacheKey('https://ava-architects.vn/')), 'utf8');
const head = html.slice(0, html.indexOf('</head>'));
const block = head.match(/<style id=["']custom-css["'][^>]*>([\s\S]*?)<\/style>/);
if (!block) { console.error('custom-css block not found'); process.exit(1); }

let css = block[1];
const at = css.indexOf(MARKER);
if (at < 0) { console.error('marker not found'); process.exit(1); }
css = css.slice(at + MARKER.length);

// Point every asset at the local copy. These live one level up from assets/css/.
css = css.replace(/url\((['"]?)(https?:\/\/ava-architects\.vn[^'")]+)\1\)/g,
  (_, q, url) => `url(${q}../${localPath(url).replace(/^assets\//, '')}${q})`);

/** Re-indent a minified stylesheet so it stays reviewable. */
function format(src) {
  let out = '';
  let depth = 0;
  let i = 0;
  while (i < src.length) {
    const ch = src[i];

    if (ch === '/' && src[i + 1] === '*') {            // keep comments verbatim
      const end = src.indexOf('*/', i + 2);
      const comment = src.slice(i, end < 0 ? src.length : end + 2);
      if (out !== '' && !out.endsWith('\n')) out += '\n';
      out += '  '.repeat(depth) + comment.trim() + '\n';
      i = end < 0 ? src.length : end + 2;
      continue;
    }
    if (ch === '{') { out = out.replace(/\s+$/, '') + ' {\n'; depth++; i++; continue; }
    if (ch === '}') { depth = Math.max(0, depth - 1); out = out.replace(/\s+$/, '') + '\n' + '  '.repeat(depth) + '}\n'; i++; continue; }
    if (ch === ';') { out += ';\n'; i++; continue; }
    if (ch === '\n' || ch === '\r') { i++; continue; }

    // start of a line: indent, and skip leading whitespace
    if (out === '' || out.endsWith('\n')) {
      if (/\s/.test(ch)) { i++; continue; }
      out += '  '.repeat(depth);
    }
    out += ch;
    i++;
  }
  return out
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^(\s*)([^\s@].*\{)$/gm, '$1$2')       // keep selectors tight
    .replace(/\}\n(?!\n|\s*\})/g, '}\n\n');          // blank line between blocks
}

const header = `/* ==========================================================================
   AVA Architects — 11. Site custom layer
   Generated by build/gen-site-custom.mjs from the site's own inline
   "Custom CSS" block — the bespoke rules the theme cannot express, covering
   fonts, nav colouring, card treatments, filter bars and the mobile overrides.
   Asset URLs are rewritten to the local copies under assets/.
   Do not edit by hand; edit the source or the generator.
   ========================================================================== */

`;

const outPath = join(ROOT, 'src/css/11-site-custom.css');
writeFileSync(outPath, header + format(css).trim() + '\n');
console.log(`wrote src/css/11-site-custom.css (${(format(css).length / 1024).toFixed(1)} KB)`);
